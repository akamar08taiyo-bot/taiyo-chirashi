as $$
begin
  update public.profiles
     set flyer_contact_name=left(trim(coalesce(p_contact_name,'')),100),
         mobile_phone=left(trim(coalesce(p_mobile_phone,'')),40)
   where id=auth.uid() and is_active;
end $$;
